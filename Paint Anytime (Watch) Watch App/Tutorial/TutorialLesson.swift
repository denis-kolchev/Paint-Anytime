import Foundation

enum TutorialLesson {
    static func compactInstruction(for step: TutorialStep) -> String {
        switch step {
        case .inactive: return ""
        case .firstStrokes: return L10n.text("Touch to draw.")
        case .holdCircle: return L10n.text("Draw a circle and hold at the end.")
        case .zoomCanvas: return L10n.text("Turn the Digital Crown to zoom.")
        case .panCanvas: return L10n.text("Drag your finger to move around.")
        case .finishCamera: return L10n.text("Tap ✓ when ready.")
        case .openTools: return L10n.text("Tap the brush settings button.")
        case .pickColor: return L10n.text("Turn the Crown to choose a color.")
        case .openCurrentPalette: return L10n.text("Tap the palette button in the corner.")
        case .addPaletteColor: return L10n.text("Tap + to add a color.")
        case .openPalettes: return L10n.text("Tap the palette button above.")
        case .findNewPalette: return L10n.text("Swipe Left to New palette.")
        case .createPalette: return L10n.text("Tap New palette.")
        case .adjustPaletteColor: return L10n.text("Drag on the wheel to pick a color.")
        case .savePaletteColor: return L10n.text("Tap ✓ to use this color.")
        case .openWidth: return L10n.text("Swipe left to Width.")
        case .setWidth: return L10n.text("Turn the Crown to change width.")
        case .openOpacity: return L10n.text("Swipe left to Opacity.")
        case .setOpacity: return L10n.text("Turn the Crown to change opacity")
        case .openTool: return L10n.text("Swipe left to Tool.")
        case .selectReed: return L10n.text("Scroll down with the Crown to choose any tool.")
        case .chooseReed: return L10n.text("Choose Reed pen to set the angle.")
        case .chooseFill: return L10n.format("Turn the Crown to choose %@.", DrawingInstrument.fill.title)
        case .chooseBlur: return L10n.format("Turn the Crown to choose %@.", DrawingInstrument.blur.title)
        case .blurCanvas: return L10n.text("Drag over your drawing to soften it.")
        case .crossMarkerLine: return L10n.text("Draw across the yellow line. The colors mix.")
        case .openDrawingSettings: return L10n.text("Tap Drawing.")
        case .openColorBlending: return L10n.text("Tap Color Blending.")
        case .chooseColorInversion: return L10n.text("Tap Color inversion.")
        case .redrawMarkerLine: return L10n.text("Draw across the yellow line again.")
        case .fillCanvas: return L10n.text("Tap to fill a connected area with the selected color and opacity.")
        case .openLayers: return L10n.text("Tap the layers button.")
        case .openLayerSettings: return L10n.text("Tap the layer settings button.")
        case .lockTransparency: return L10n.text("Tap the lock to paint only over existing strokes.")
        case .closeLayerSettings, .closeLayers: return L10n.text("Tap Back.")
        case .paintOverStroke: return L10n.text("Paint over your strokes. The new color stays inside them.")
        case .addLayer: return L10n.text("Tap + to add a layer.")
        case .moveLayerDown: return L10n.text("Hold the new layer and drag it down.")
        case .drawBehindStroke: return L10n.text("Draw behind your strokes.")
        case .openAngle: return L10n.text("Swipe left to Angle.")
        case .setAngle: return L10n.text("Turn the Crown to change the nib angle.")
        case .closeTools: return L10n.text("Tap ✓ to start drawing.")
        case .reedStrokes: return L10n.text("Try your new brush.")
        case .openLasso: return L10n.text("Tap the lasso button.")
        case .selectLasso: return L10n.text("Circle part of your drawing.")
        case .transformLasso: return L10n.text("Move or resize the selection.")
        case .finishLasso: return L10n.text("Tap ✓ when ready.")
        case .history: return L10n.text("Use the arrows to undo and redo.")
        case .saveDrawing: return L10n.text("Tap the button to save your drawing.")
        case .openMenu: return L10n.text("Tap ••• to visit the gallery.")
        case .openGallery: return L10n.text("Tap Gallery to see your saved drawings.")
        case .galleryFullscreen: return L10n.text("Turn the Crown or double-tap a picture.")
        case .deleteDrawing: return L10n.text("Tap the trash to delete a picture.")
        case .returnToCanvas: return L10n.text("Tap Back to leave the gallery.")
        case .clearCanvas: return L10n.text("Tap the broom to clear the canvas.")
        case .openCanvasSettings: return L10n.text("Tap Canvas.")
        case .openPerspective: return L10n.text("Tap Perspective guides.")
        case .choosePerspective: return L10n.text("Tap 1 to show the guides.")
        case .perspectiveStroke: return L10n.text("Start a stroke on a guide. It follows the line.")
        case .openCanvasSize: return L10n.text("Tap Canvas size.")
        case .openCrop: return L10n.text("Tap Crop.")
        case .applyCrop: return L10n.text("Turn the Crown to trim the edges, then tap ✓.")
        case .startSelection: return L10n.text("Tap ✓ at the top to select pictures.")
        case .selectDrawings: return L10n.text("Tap two pictures.")
        case .favoriteSelection: return L10n.text("Tap ♡ to add them to favorites.")
        case .chapterComplete: return L10n.text("Chapter complete! Tap the arrow for the next chapter.")
        case .finished: return L10n.text("Well done! Tutorial complete. Tap ✓ below to finish.")
        }
    }
    static func description(for step: TutorialStep) -> String { compactInstruction(for: step) }
}
